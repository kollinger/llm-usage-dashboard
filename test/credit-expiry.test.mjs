import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { createCreditExpiryStore, creditExpiryAlert, validDate } = require("../lib/credit-expiry");
const directory = await fs.mkdtemp(path.join(os.tmpdir(), "credit-expiry-"));
process.env.LLM_USAGE_DATA_DIR = directory;
process.env.CODEX_HOME = path.join(directory, "codex");
process.env.CODEX_LIVE_RATE_LIMITS = "false";
const { app, _test } = require("../server");
const file = path.join(directory, "credit-expiry.json");
let server;
try {
  const store = createCreditExpiryStore(file), a = "a".repeat(64), b = "b".repeat(64);
  for (const date of ["2026-02-30", "2026-13-01", "December 31", "2026-12-31T00:00:00Z", "2026-2-1"]) assert.equal(validDate(date), false);
  assert.equal(validDate("2028-02-29"), true);
  await Promise.all([store.set(a, "2026-12-31"), store.set(b, "2027-01-15")]);
  assert.equal(await createCreditExpiryStore(file).get(a), "2026-12-31", "persists across restart");
  assert.equal(await store.get(b), "2027-01-15", "accounts stay separate");
  if (process.platform !== "win32") assert.equal((await fs.stat(file)).mode & 0o777, 0o600);
  await store.set(a, null); assert.equal(await store.get(a), null); assert.equal(await store.get(b), "2027-01-15");
  const row = { balance: 63000, expiresOn: "2026-12-31", expirySource: "manual" };
  const at = (date) => new Date(`${date}T12:00:00`);
  assert.equal(creditExpiryAlert(row, at("2026-11-30")), null);
  assert.equal(creditExpiryAlert(row, at("2026-12-01")).daysRemaining, 30);
  assert.equal(creditExpiryAlert(row, at("2026-12-02")).id, creditExpiryAlert(row, at("2026-12-01")).id);
  assert.notEqual(creditExpiryAlert(row, at("2026-12-24")).id, creditExpiryAlert(row, at("2026-12-01")).id);
  assert.equal(creditExpiryAlert(row, at("2026-12-30")).daysRemaining, 1);
  assert.equal(creditExpiryAlert(row, at("2026-12-31")).daysRemaining, 0);
  assert.equal(creditExpiryAlert(row, at("2027-01-01")), null);
  assert.equal(creditExpiryAlert({ ...row, balance: 0 }, at("2026-12-24")), null);
  assert.equal(creditExpiryAlert({ ...row, expiresOn: null }, at("2026-12-24")), null);
  assert.equal(creditExpiryAlert({ ...row, expiresOn: "2026-11-01" }, at("2026-10-25")).daysRemaining, 7, "calendar dates survive DST changes");
  const currentRow = { ...row, expiresOn: new Date(Date.now() + 7 * 86400000).toISOString().slice(0, 10) };
  assert.equal(_test.buildNotificationAlerts({}, { codex: { creditRows: [currentRow] } })[0].type, "credit_expiry");
  assert.equal(_test.codexCreditRowsFromLive({ credits: { hasCredits: true, balance: "0" } })[0].balance, 0);
  assert.equal(_test.codexCreditRowsFromLive({ credits: { unlimited: true } })[0].balance, undefined);
  await fs.mkdir(process.env.CODEX_HOME);
  const auth = (account) => fs.writeFile(path.join(process.env.CODEX_HOME, "auth.json"), JSON.stringify({ tokens: { account_id: account } }));
  await auth("fixture-account-a");
  server = await new Promise((resolve) => { const listening = app.listen(0, "127.0.0.1", () => resolve(listening)); });
  const url = `http://127.0.0.1:${server.address().port}/api/credits/codex-expiry`;
  const first = await (await fetch(url)).json();
  const live = await _test.readScopedCodexLiveRateLimits({ request: async () => ({ rateLimits: { credits: { balance: "63000" } } }) });
  assert.equal(live.source.creditScope, first.context, "interactive and background credit reads retain the current account scope");
  const save = (context, expiresOn) => fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ context, expiresOn }) });
  assert.equal((await save(first.context, "2026-02-30")).status, 400);
  assert.equal((await save(first.context, "2026-12-31")).status, 200);
  assert.equal((await (await fetch(url)).json()).expiresOn, "2026-12-31");
  const usage = { codex: { creditScope: first.context, creditRows: [{ key: "codexCredits", balance: 63000 }] } };
  assert.equal((await _test.applyCodexCreditExpiry(usage)).codex.creditRows[0].expiresOn, "2026-12-31");
  assert.equal(usage.codex.creditRows[0].expiresOn, undefined, "does not mutate cached usage");
  await auth("fixture-account-b");
  assert.equal((await (await fetch(url)).json()).expiresOn, null);
  assert.equal((await save(first.context, "2027-01-15")).status, 409, "stale dialog cannot save for a different account");
  assert.equal((await _test.applyCodexCreditExpiry(usage)).codex.creditRows[0].expiresOn, null, "old cached credit balance cannot inherit another account's date");
  await auth("fixture-account-a");
  assert.equal((await save(first.context, null)).status, 200);
} finally {
  if (server) await new Promise((resolve) => server.close(resolve));
  await fs.rm(directory, { recursive: true, force: true });
}
console.log("Credit expiry: calendar boundaries, stages, persistence, account isolation and API validation passed.");
